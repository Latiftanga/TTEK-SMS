from __future__ import annotations

import re
import uuid
from datetime import datetime

from pydantic import BaseModel, EmailStr, field_validator

from app.models.school import EmailProvider, EmailStatus, SchoolOwnership, SchoolType, SmsProvider

_HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}$")
_SUBDOMAIN_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,48}[a-z0-9]$")
_DOMAIN_RE = re.compile(r"^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$")


class SchoolCreate(BaseModel):
    name: str
    short_name: str | None = None
    school_code: str
    school_type: SchoolType
    region_id: uuid.UUID
    district_id: uuid.UUID
    phone: str | None = None
    email: EmailStr | None = None
    address: str | None = None
    motto: str | None = None
    established_year: int | None = None
    subdomain: str | None = None
    custom_domain: str | None = None
    brand_color: str = "#1e40af"
    has_boarding: bool = False

    @field_validator("school_code")
    @classmethod
    def code_uppercase(cls, v: str) -> str:
        return v.strip().upper()

    @field_validator("subdomain")
    @classmethod
    def subdomain_valid(cls, v: str | None) -> str | None:
        if v is None:
            return v
        v = v.lower().strip()
        if not _SUBDOMAIN_RE.match(v):
            raise ValueError("subdomain must be 3-50 lowercase letters, numbers, or hyphens")
        return v

    @field_validator("custom_domain")
    @classmethod
    def custom_domain_valid(cls, v: str | None) -> str | None:
        if v is None:
            return v
        v = v.lower().strip()
        if not _DOMAIN_RE.match(v):
            raise ValueError("custom_domain must be a valid fully-qualified domain name")
        return v

    @field_validator("brand_color")
    @classmethod
    def color_valid(cls, v: str) -> str:
        if not _HEX_RE.match(v):
            raise ValueError("brand_color must be a 6-digit hex colour, e.g. #1e40af")
        return v.lower()


