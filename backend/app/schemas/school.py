class SchoolBranding(BaseModel):
    """
    Public branding data returned by GET /schools/public/{subdomain}.

    No auth required.  Contains only what the login screen needs — no
    internal IDs, contact details, or sensitive config.

    school_code is included because ADMISSION_ID login requires the GES code
    (e.g. "PRESEC"), which may differ from the URL subdomain slug ("presec-gh").

    LIGHT / DARK MODE
    -----------------
    brand_color is the single hex colour the school admin chose.
    The frontend derives the full palette from it:
      - Light mode base: warm off-white #f8f7f4 (not glaring white)
      - Dark mode base:  deep charcoal  #111318 (not pure black)
      - Tints/shades of brand_color auto-generated by the color utility
      - Foreground (white vs black) chosen by luminance contrast ratio
    Admins cannot break the UI — they only control brand_color.
    """
    school_name: str
    short_name: str | None
    school_type: SchoolType
    motto: str | None
    logo_url: str | None   # absolute URL, ready for <img src>
    brand_color: str
    school_code: str

    model_config = {"from_attributes": True}


class SchoolByDomainResult(SchoolBranding):
    """
    Returned by GET /schools/by-domain when a school is found for a custom domain.

    Extends SchoolBranding with the subdomain slug so the frontend can store
    the school identity consistently regardless of how it was reached.
    """
    subdomain: str | None = None


